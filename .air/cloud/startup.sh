#!/usr/bin/env bash
# Air cloud environment startup script for external-secrets.
#
# Installs the toolchain needed by the Makefile targets (`make test`, `make reviewable`,
# `make check-diff`), builds the repo-local tools into ./bin, downloads the envtest
# Kubernetes binaries and primes the Go module/build caches and Docker images.
# In WARMUP mode it finishes with `healthcheck`, which runs a real envtest-backed test.
set -euo pipefail

if [ "${AIR_STARTUP_MODE:-}" = warmup ]; then WARMUP=1; else WARMUP=; fi

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_DIR"

HELM_VERSION="v3.17.3"          # matches .github/workflows
KUBERNETES_VERSION="1.33.x"     # matches KUBERNETES_VERSION in Makefile
LOCAL_TOOLS="$HOME/.local/bin"
ENV_FILE="$HOME/.air-external-secrets-env.sh"

log() { echo "[startup $(date +%H:%M:%S)] $*"; }

SUDO=""
if [ "$(id -u)" -ne 0 ]; then SUDO="sudo -E"; fi

# ---------------------------------------------------------------------------
# System packages: make + a C toolchain (go test -race needs cgo), jq, unzip.
# ---------------------------------------------------------------------------
install_system_packages() {
  local missing=()
  command -v make >/dev/null || missing+=(make)
  command -v gcc >/dev/null || missing+=(gcc libc6-dev)
  command -v jq >/dev/null || missing+=(jq)
  command -v unzip >/dev/null || missing+=(unzip)
  if [ ${#missing[@]} -eq 0 ]; then
    log "system packages already present"
    return
  fi
  log "installing system packages: ${missing[*]}"
  $SUDO apt-get update -q
  DEBIAN_FRONTEND=noninteractive $SUDO apt-get install -y -q --no-install-recommends "${missing[@]}"
}

# ---------------------------------------------------------------------------
# User-space CLI tools: helm, terraform.
# ---------------------------------------------------------------------------
install_helm() {
  if [ -x "$LOCAL_TOOLS/helm" ] && "$LOCAL_TOOLS/helm" version --short 2>/dev/null | grep -q "^${HELM_VERSION}"; then
    log "helm ${HELM_VERSION} already installed"
    return
  fi
  log "installing helm ${HELM_VERSION}"
  local tmp; tmp="$(mktemp -d)"
  curl -fsSL "https://get.helm.sh/helm-${HELM_VERSION}-linux-amd64.tar.gz" | tar -xz -C "$tmp"
  install -m 0755 "$tmp/linux-amd64/helm" "$LOCAL_TOOLS/helm"
  rm -rf "$tmp"
}

install_terraform() {
  if [ -x "$LOCAL_TOOLS/terraform" ]; then
    log "terraform already installed ($("$LOCAL_TOOLS/terraform" version | head -1))"
    return
  fi
  local version
  version="$(curl -fsSL https://checkpoint-api.hashicorp.com/v1/check/terraform | jq -r .current_version)"
  log "installing terraform ${version}"
  local tmp; tmp="$(mktemp -d)"
  curl -fsSL -o "$tmp/tf.zip" "https://releases.hashicorp.com/terraform/${version}/terraform_${version}_linux_amd64.zip"
  unzip -q -o "$tmp/tf.zip" terraform -d "$tmp"
  install -m 0755 "$tmp/terraform" "$LOCAL_TOOLS/terraform"
  rm -rf "$tmp"
}

# ---------------------------------------------------------------------------
# Login-shell environment: put ~/.local/bin and the Go toolchain on PATH and
# expose KUBEBUILDER_ASSETS for running envtest suites directly.
# ---------------------------------------------------------------------------
write_shell_env() {
  local assets="$1"
  cat > "$ENV_FILE" <<EOF
# Generated by .air/cloud/startup.sh
case ":\$PATH:" in *":$LOCAL_TOOLS:"*) ;; *) export PATH="$LOCAL_TOOLS:\$PATH" ;; esac
case ":\$PATH:" in *":$(go env GOPATH)/bin:"*) ;; *) export PATH="\$PATH:$(go env GOPATH)/bin" ;; esac
export KUBEBUILDER_ASSETS="$assets"
EOF
  local marker="# air-external-secrets-env"
  local line="[ -f \"$ENV_FILE\" ] && . \"$ENV_FILE\" $marker"
  local profile=""
  for f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
    if [ -f "$f" ]; then profile="$f"; break; fi
  done
  [ -n "$profile" ] || { profile="$HOME/.profile"; touch "$profile"; }
  for f in "$profile" "$HOME/.bashrc"; do
    grep -qF "$marker" "$f" 2>/dev/null || echo "$line" >> "$f"
  done
}

# ---------------------------------------------------------------------------
# Healthcheck: toolchain works and a real envtest-backed controller test passes.
# ---------------------------------------------------------------------------
healthcheck() {
  log "healthcheck: verifying tools"
  make --version | head -1
  gcc --version | head -1
  go version
  helm version --short
  terraform version | head -1
  docker info --format 'docker server {{.ServerVersion}}'
  ./bin/controller-gen --version
  ./bin/golangci-lint version
  ./bin/external-secrets --help >/dev/null

  log "healthcheck: running envtest suite pkg/controllers/webhookconfig"
  local snap; snap="$(mktemp)"
  ./hack/modfiles.sh snapshot "$snap"
  local rc=0
  (
    make go-work
    KUBEBUILDER_ASSETS="$KUBEBUILDER_ASSETS" go test -tags all_providers -race -count=1 ./pkg/controllers/webhookconfig/...
  ) || rc=$?
  ./hack/modfiles.sh restore "$snap"
  rm -f "$snap"
  if [ "$rc" -ne 0 ]; then
    log "healthcheck FAILED: envtest suite exited with $rc"
    return "$rc"
  fi

  if ! git diff --quiet; then
    log "healthcheck FAILED: setup left the working tree dirty:"
    git status --short
    return 1
  fi
  log "healthcheck passed"
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
mkdir -p "$LOCAL_TOOLS"
export PATH="$LOCAL_TOOLS:$PATH"

install_system_packages
install_helm
install_terraform

log "go toolchain: $(go version)"
export PATH="$PATH:$(go env GOPATH)/bin"

log "building repo-local tools (controller-gen, setup-envtest, golangci-lint, cty)"
make controller-gen envtest golangci-lint cty

log "downloading envtest binaries for Kubernetes ${KUBERNETES_VERSION}"
KUBEBUILDER_ASSETS="$(./bin/setup-envtest use "$KUBERNETES_VERSION" -p path --bin-dir ./bin)"
export KUBEBUILDER_ASSETS
log "KUBEBUILDER_ASSETS=$KUBEBUILDER_ASSETS"

write_shell_env "$KUBEBUILDER_ASSETS"

if [ -n "$WARMUP" ]; then
  # Expensive, cacheable work: persisted in the warm-up snapshot.
  log "priming Go module and build caches across all workspace modules"
  snap="$(mktemp)"
  ./hack/modfiles.sh snapshot "$snap"
  prime_rc=0
  (
    make go-work
    go build -tags all_providers -o bin/external-secrets .
    # Compile (but do not run) every unit test package the way `make test` does.
    go test -tags all_providers -race -count=1 -run '^$' work >/dev/null
  ) || prime_rc=$?
  ./hack/modfiles.sh restore "$snap"
  rm -f "$snap"
  [ "$prime_rc" -eq 0 ] || { log "priming Go caches failed ($prime_rc)"; exit "$prime_rc"; }

  log "installing helm plugins"
  make helm.schema.plugin helm.unittest.plugin

  log "pre-pulling / building Docker images used by make reviewable"
  docker pull -q docker.io/jnorwood/helm-docs:v1.14.2
  docker pull -q docker.io/apache/skywalking-eyes:0.9.0@sha256:b503ab18f5b29d7e04abe05668faf42f1023f9347b095d97592a5208102588ef
  make -C hack/api-docs image

  healthcheck
fi

log "startup complete"
